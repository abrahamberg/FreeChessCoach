// Draws the pictures the shared review's preview image is put together from
// (apps/api/src/services/review-share/share-image.ts) and writes them, as
// base64 PNG, to src/services/review-share/*-sprite.generated.ts (one file
// each, to stay under the repo's 50 KB per file). The api
// draws the preview in plain JS at request time (no native image library in
// the image), so the piece set and the words are drawn once, here.
//
// Run from the repo root: node apps/api/scripts/build-share-image-sprites.mjs
// Needs Playwright and Chromium, resolved from the global npm root like
// scripts/capture-marketing-shots.mjs.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { defaultPieces } from 'react-chessboard';

const globalRequire = createRequire(join(execSync('npm root -g').toString().trim(), '/'));
const { chromium } = globalRequire('playwright');

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(HERE, '..', 'src', 'services', 'review-share');
/** Keep in step with share-image.ts. */
const SQUARE = 70;
const PIECE_ORDER = ['wP', 'wN', 'wB', 'wR', 'wQ', 'wK', 'bP', 'bN', 'bB', 'bR', 'bQ', 'bK'];
const BANNER = { width: 540, height: 380 };

function pieceStrip() {
  const pieces = PIECE_ORDER.map((code) => {
    const markup = renderToStaticMarkup(defaultPieces[code]({ svgStyle: { width: SQUARE, height: SQUARE, display: 'block' } }));
    return `<div style="width:${SQUARE}px;height:${SQUARE}px">${markup}</div>`;
  });
  return `<div id="shot" style="display:flex;width:${SQUARE * PIECE_ORDER.length}px">${pieces.join('')}</div>`;
}

function banner() {
  return `
    <div id="shot" style="width:${BANNER.width}px;height:${BANNER.height}px;display:flex;flex-direction:column;justify-content:center;gap:30px;font-family:'Inter Tight',Inter,'DejaVu Sans',sans-serif;color:#26241e">
      <div style="display:flex;align-items:center;gap:16px;font-size:34px;font-weight:700">
        <span style="width:18px;height:48px;border-radius:5px;background:#3d6b48"></span>FreeChess Coach
      </div>
      <div style="font-size:52px;font-weight:800;line-height:1.12">Every move of this game, explained in words.</div>
      <div style="align-self:flex-start;background:#3d6b48;color:#fff;font-size:30px;font-weight:700;padding:16px 28px;border-radius:14px">Review your own game, free</div>
    </div>`;
}

async function shoot(page, html) {
  await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${html}</body></html>`);
  const buffer = await page.locator('#shot').screenshot({ omitBackground: true });
  return buffer.toString('base64');
}

const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });
const pieces = await shoot(page, pieceStrip());
const words = await shoot(page, banner());
await browser.close();

const HEADER = '// Generated by apps/api/scripts/build-share-image-sprites.mjs; do not edit.';
writeFileSync(
  join(OUT_DIR, 'piece-sprite.generated.ts'),
  [
    HEADER,
    `/** react-chessboard's piece set at ${SQUARE}px, one row in this order. */`,
    `export const PIECE_ORDER = ${JSON.stringify(PIECE_ORDER)} as const;`,
    `export const PIECE_SPRITE_PNG = '${pieces}';`,
    ''
  ].join('\n')
);
writeFileSync(
  join(OUT_DIR, 'banner-sprite.generated.ts'),
  [HEADER, `/** The words beside the board, ${BANNER.width} by ${BANNER.height}, transparent. */`, `export const BANNER_PNG = '${words}';`, ''].join('\n')
);
console.log(`wrote ${OUT_DIR}/*-sprite.generated.ts`);
